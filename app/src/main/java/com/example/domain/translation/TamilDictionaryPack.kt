    fun getWordMeaning(word: String): String? {
        val clean = word.lowercase(Locale.ROOT).trim()
        WORDS[clean]?.let { return it }

        // Suffix / Inflection handling:
        // 1. Plural: -ies -> -y, -es, -s
        if (clean.endsWith("ies") && clean.length > 4) {
            val stem = clean.substring(0, clean.length - 3) + "y"
            WORDS[stem]?.let { return it + "க்கள்" }
        }
        if (clean.endsWith("es") && clean.length > 3) {
            val stem = clean.substring(0, clean.length - 2)
            WORDS[stem]?.let { return it + "க்கள்" }
        }
        if (clean.endsWith("s") && clean.length > 2 && !clean.endsWith("ss")) {
            val stem = clean.substring(0, clean.length - 1)
            WORDS[stem]?.let { return it + "க்கள்" }
        }

        // 2. Past tense: -ied -> -y, -ed, -d
        if (clean.endsWith("ied") && clean.length > 4) {
            val stem = clean.substring(0, clean.length - 3) + "y"
            WORDS[stem]?.let { return it + "ப்பட்டது" }
        }
        if (clean.endsWith("ed") && clean.length > 3) {
            val stem = clean.substring(0, clean.length - 2)
            WORDS[stem]?.let { return it + "ப்பட்டது" }
            val stemD = clean.substring(0, clean.length - 1)
            WORDS[stemD]?.let { return it + "ப்பட்டது" }
        }

        // 3. Continuous: -ing
        if (clean.endsWith("ing") && clean.length > 4) {
            val stem = clean.substring(0, clean.length - 3)
            WORDS[stem]?.let { return it + "கிறது" }
            val stemWithE = stem + "e"
            WORDS[stemWithE]?.let { return it + "கிறது" }
        }

        // 4. Adverb: -ly
        if (clean.endsWith("ly") && clean.length > 3) {
            val stem = clean.substring(0, clean.length - 2)
            WORDS[stem]?.let { return it + "மாக" }
        }

        return null
    }
